export function getRecommendedAccessoriesForSuit(suitColor: string, category: string): AccessorySuggestion[] {
  const suitColorLower = suitColor.toLowerCase();
  const categoryLower = category.toLowerCase();

  // Pick best matching accessory from each category
  const categories: ("earrings" | "necklaces" | "bangles" | "handbags" | "footwear")[] = [
    "earrings",
    "necklaces",
    "bangles",
    "handbags",
    "footwear",
  ];

  return categories.map((cat) => {
    const itemsInCat = ALL_ACCESSORIES.filter((item) => item.category === cat);
    
    // Find best match based on recommendedColors
    const matched = itemsInCat.find((item) =>
      item.recommendedColors.some((c) => suitColorLower.includes(c.toLowerCase()) || c.toLowerCase().includes(suitColorLower))
    );

    if (matched) return matched;

    // Secondary fallback based on category style
    if (categoryLower.includes("cotton") || categoryLower.includes("college") || categoryLower.includes("daily")) {
      return itemsInCat[itemsInCat.length - 1]; // usually the more relaxed/minimal option
    }

    return itemsInCat[0];
  });
}
